static NSPasteboard *clipboardBoard(void) {
#ifdef TOOKI_CLIPBOARD_TEST
    return [NSPasteboard pasteboardWithName:@"dev.tooki.clipboard-tests"];
#else
    return NSPasteboard.generalPasteboard;
#endif
}
static NSInteger observedChange = -1;
static pid_t pasteTarget = 0;
static id activationObserver = nil;

extern NSDictionary *tooki_preview(NSString *operation, NSDictionary *args);
extern id tooki_image_preview(NSString *path);

static NSDictionary *failure(NSString *message) { return @{ @"error": message ?: @"Native operation failed" }; }
static NSString *str(id value) { return [value isKindOfClass:NSString.class] ? value : @""; }
static void rememberTarget(void) {
    NSRunningApplication *front = NSWorkspace.sharedWorkspace.frontmostApplication;
    if (front && front.processIdentifier != NSProcessInfo.processInfo.processIdentifier) pasteTarget = front.processIdentifier;
}
static void postPaste(void) {
    CGEventRef down = CGEventCreateKeyboardEvent(NULL, 9, true);
    CGEventRef up = CGEventCreateKeyboardEvent(NULL, 9, false);
    CGEventSetFlags(down, kCGEventFlagMaskCommand); CGEventSetFlags(up, kCGEventFlagMaskCommand);
    CGEventPost(kCGHIDEventTap, down); CGEventPost(kCGHIDEventTap, up);
    CFRelease(down); CFRelease(up);
}
pid_t tooki_clipboard_target_pid(void) { return pasteTarget; }
static id paste(pid_t destination) {
    if (!tooki_accessibility_granted()) return failure(@"Enable Accessibility for Tooki in System Settings to paste into another app.");
    NSRunningApplication *target = [NSRunningApplication runningApplicationWithProcessIdentifier:destination];
    if (!target || target.terminated) return failure(@"The previous application is no longer available. Copy the item and paste manually.");
    if (target.active) { postPaste(); return @YES; }
    NSNotificationCenter *center = NSWorkspace.sharedWorkspace.notificationCenter;
    if (activationObserver) [center removeObserver:activationObserver];
    activationObserver = [center addObserverForName:NSWorkspaceDidActivateApplicationNotification object:nil queue:NSOperationQueue.mainQueue usingBlock:^(NSNotification *note) {
        NSRunningApplication *active = note.userInfo[NSWorkspaceApplicationKey];
        if (active.processIdentifier == target.processIdentifier) {
            [NSWorkspace.sharedWorkspace.notificationCenter removeObserver:activationObserver]; activationObserver = nil; postPaste();
        }
    }];
    if (![target activateWithOptions:0]) { [center removeObserver:activationObserver]; activationObserver=nil; return failure(@"Could not activate the previous application."); }
    // Cleanup only; pasting is driven by activation, not a guessed delay.
    id observer = activationObserver;
    dispatch_after(dispatch_time(DISPATCH_TIME_NOW, 3*NSEC_PER_SEC), dispatch_get_main_queue(), ^{ if (activationObserver == observer) { [center removeObserver:observer]; activationObserver=nil; } });
    return @YES;
}
static id capture(NSDictionary *args) {
    rememberTarget();
    NSPasteboard *pb = clipboardBoard();
    NSInteger change = pb.changeCount;
    if (observedChange < 0) { observedChange=change; return NSNull.null; }
    if (change == observedChange) return NSNull.null;
    observedChange=change;
    if (![args[@"enabled"] boolValue]) return NSNull.null;
    for (NSString *type in @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType", @"com.agilebits.onepassword"]) {
        if ([pb.types containsObject:type]) return NSNull.null;
    }
    NSRunningApplication *source=NSWorkspace.sharedWorkspace.frontmostApplication;
    NSString *bundle=source.bundleIdentifier ?: @"";
    if ([args[@"ignoredApps"] containsObject:bundle]) return NSNull.null;
    NSMutableDictionary *result=[@{@"source":source.localizedName ?: @"Unknown", @"sourceId":bundle} mutableCopy];
    NSArray<NSURL *> *urls=[pb readObjectsForClasses:@[NSURL.class] options:@{NSPasteboardURLReadingFileURLsOnlyKey:@YES}];
    if (urls.count) {
        NSMutableArray *files=[NSMutableArray array]; unsigned long long bytes=0;
        for (NSURL *url in urls) { [files addObject:url.path]; NSNumber *size; [url getResourceValue:&size forKey:NSURLFileSizeKey error:nil]; bytes+=size.unsignedLongLongValue; }
        result[@"files"]=files; result[@"bytes"]=@(bytes);
    } else {
        NSString *text=[pb stringForType:NSPasteboardTypeString];
        if (text.length) {
            if ([text lengthOfBytesUsingEncoding:NSUTF8StringEncoding] > 4*1024*1024) return NSNull.null;
            result[@"text"]=text; result[@"bytes"]=@([text lengthOfBytesUsingEncoding:NSUTF8StringEncoding]);
            NSData *html=[pb dataForType:NSPasteboardTypeHTML]; NSData *rtf=[pb dataForType:NSPasteboardTypeRTF];
            if (html.length && html.length<=4*1024*1024) result[@"html"]=[html base64EncodedStringWithOptions:0];
            if (rtf.length && rtf.length<=4*1024*1024) result[@"rtf"]=[rtf base64EncodedStringWithOptions:0];
        } else if ([args[@"images"] boolValue]) {
            NSData *png=[pb dataForType:NSPasteboardTypePNG];
            NSData *data=png ?: [pb dataForType:NSPasteboardTypeTIFF];
            if (!data.length || data.length>32*1024*1024) return NSNull.null;
            NSBitmapImageRep *rep=[NSBitmapImageRep imageRepWithData:data];
            if (!rep || rep.pixelsWide*rep.pixelsHigh>100000000) return NSNull.null;
            // Preserve the source PNG's compression and metadata; only convert TIFF.
            if (!png) png=[rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
            if (!png || png.length>32*1024*1024) return NSNull.null;
            NSString *path=[str(args[@"directory"]) stringByAppendingPathComponent:[NSUUID.UUID.UUIDString stringByAppendingString:@".png"]];
            NSError *error; if (![png writeToFile:path options:NSDataWritingAtomic error:&error]) return failure(error.localizedDescription);
            result[@"image"]=path;result[@"width"]=@(rep.pixelsWide);result[@"height"]=@(rep.pixelsHigh);result[@"bytes"]=@(png.length);
        } else return NSNull.null;
    }
    if (pb.changeCount != change) { if(result[@"image"]) [NSFileManager.defaultManager removeItemAtPath:result[@"image"] error:nil]; return NSNull.null; }
    return result;
}
static NSArray<NSURL *> *fileURLs(NSArray *paths) {
    NSMutableArray *urls=[NSMutableArray array]; for (NSString *path in paths) [urls addObject:[NSURL fileURLWithPath:path]]; return urls;
}
static id perform(NSString *op, NSDictionary *args) {
    if ([op isEqual:@"imagePreview"]) return tooki_image_preview(str(args[@"path"]));
    if ([op isEqual:@"capture"]) return capture(args);
    if ([op isEqual:@"rememberTarget"]) { rememberTarget(); return @YES; }
    if ([op isEqual:@"paste"]) return paste(args[@"targetPid"] ? [args[@"targetPid"] intValue] : pasteTarget);
    if ([op isEqual:@"ocr"]) {
        VNRecognizeTextRequest *request=[VNRecognizeTextRequest new]; request.recognitionLevel=VNRequestTextRecognitionLevelAccurate; request.usesLanguageCorrection=YES;
        if (@available(macOS 13.0,*)) request.automaticallyDetectsLanguage=YES;
        VNImageRequestHandler *handler=[[VNImageRequestHandler alloc] initWithURL:[NSURL fileURLWithPath:str(args[@"path"])] options:@{}];
        NSError *error; if (![handler performRequests:@[request] error:&error]) return failure(error.localizedDescription);
        NSMutableArray *lines=[NSMutableArray array]; for (VNRecognizedTextObservation *line in request.results) { NSString *text=[line topCandidates:1].firstObject.string; if(text) [lines addObject:text]; }
        return [lines componentsJoinedByString:@"\n"];
    }
    if ([op isEqual:@"copy"]) {
        NSPasteboard *pb=clipboardBoard();
        NSString *mode=str(args[@"mode"]); NSDictionary *item=args[@"item"];
        if ([mode isEqual:@"ocr"] || [mode isEqual:@"paths"] || [mode isEqual:@"plain"]) {
            NSString *text;
            if ([mode isEqual:@"paths"]) {
                text = [item[@"files"] count] ? [item[@"files"] componentsJoinedByString:@"\n"] : str(item[@"image"]);
                if (!text.length) return failure(@"This clipboard item has no file on disk.");
            } else {
                text = [mode isEqual:@"ocr"] ? str(item[@"ocr"]) : str(item[@"content"]);
            }
            [pb clearContents];
            if (![pb setString:text forType:NSPasteboardTypeString]) return failure(@"Could not write to the clipboard.");
        } else if ([item[@"files"] count]) { [pb clearContents]; [pb writeObjects:fileURLs(item[@"files"])]; }
        else if (str(item[@"image"]).length) {
            NSData *image=[NSData dataWithContentsOfFile:item[@"image"]]; if (!image) return failure(@"The image is no longer available.");
            [pb clearContents]; [pb setData:image forType:NSPasteboardTypePNG];
        } else {
            [pb clearContents]; [pb setString:str(item[@"content"]) forType:NSPasteboardTypeString];
            for (NSString *format in @[@"html",@"rtf"]) {
                NSData *data=[[NSData alloc] initWithBase64EncodedString:str(item[format]) options:0];
                if (data.length) [pb setData:data forType:[format isEqual:@"html"] ? NSPasteboardTypeHTML : NSPasteboardTypeRTF];
            }
        }
        [pb setString:@"Tooki" forType:@"org.nspasteboard.AutoGeneratedType"];
        observedChange=pb.changeCount; return @YES;
    }
    if ([@[@"preview", @"previewUpdate", @"previewClose", @"previewCloseOwner", @"previewActive"] containsObject:op])
        return tooki_preview(op, args);
    NSURL *url=[str(args[@"url"]) length] ? [NSURL URLWithString:args[@"url"]] : [NSURL fileURLWithPath:str(args[@"path"])];
    if ([op isEqual:@"apps"]) {
        NSWorkspace *ws=NSWorkspace.sharedWorkspace; NSURL *preferred=[ws URLForApplicationToOpenURL:url];
        NSMutableArray *result=[NSMutableArray array]; NSMutableSet *seen=[NSMutableSet set];
        NSArray *apps=[ws URLsForApplicationsToOpenURL:url];
        if(preferred) apps=[@[preferred] arrayByAddingObjectsFromArray:apps ?: @[]];
        for (NSURL *app in apps) { if([seen containsObject:app.path])continue; [seen addObject:app.path]; [result addObject:@{@"path":app.path,@"name":[NSFileManager.defaultManager displayNameAtPath:app.path],@"isDefault":@([app isEqual:preferred])}]; }
        return result;
    }
    if ([op isEqual:@"open"]) {
        NSArray *urls=[args[@"paths"] count] ? fileURLs(args[@"paths"]) : @[url];
        NSString *app=str(args[@"app"]);
        if(app.length) { NSWorkspaceOpenConfiguration *config=NSWorkspaceOpenConfiguration.configuration; [NSWorkspace.sharedWorkspace openURLs:urls withApplicationAtURL:[NSURL fileURLWithPath:app] configuration:config completionHandler:nil]; }
        else for (NSURL *target in urls) if(![NSWorkspace.sharedWorkspace openURL:target]) return failure(@"Could not open the item.");
        return @YES;
    }
    return failure(@"Unsupported native clipboard action.");
}
bool tooki_clipboard_copy_expansion(NSString *text) {
    return [perform(@"copy", @{@"item":@{@"content":text}, @"mode":@"plain"}) isEqual:@YES];
}
char *tooki_clipboard(const char *operation, const char *input) {
    @autoreleasepool {
        @try {
            NSData *data=[str([NSString stringWithUTF8String:input]) dataUsingEncoding:NSUTF8StringEncoding];
            NSDictionary *args=[NSJSONSerialization JSONObjectWithData:data options:0 error:nil] ?: @{};
            id result=perform([NSString stringWithUTF8String:operation],args);
            NSData *json=[NSJSONSerialization dataWithJSONObject:result ?: NSNull.null options:NSJSONWritingFragmentsAllowed error:nil];
            return strdup([[NSString alloc] initWithData:json encoding:NSUTF8StringEncoding].UTF8String ?: "null");
        } @catch(NSException *exception) {
            NSData *json=[NSJSONSerialization dataWithJSONObject:failure(exception.reason) options:0 error:nil];
            return strdup([[NSString alloc] initWithData:json encoding:NSUTF8StringEncoding].UTF8String);
        }
    }
}
void tooki_clipboard_free(char *value) { free(value); }
