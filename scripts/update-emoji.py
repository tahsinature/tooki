#!/usr/bin/env python3
"""Regenerates Sources/TookiKit/Emoji/EmojiData.swift from the latest emojibase-data.

emojibase (MIT, https://emojibase.dev) is built from Unicode's emoji and CLDR data, and adds
GitHub-style shortcodes. Run this after a new Unicode emoji release, then build and test.
Emoji newer than the running macOS are hidden at runtime, so updating early is safe.

    scripts/update-emoji.py           # latest version
    scripts/update-emoji.py 18.0.0    # a specific version
"""
import json
import pathlib
import sys
import urllib.request

version = sys.argv[1] if len(sys.argv) > 1 else "latest"
base = f"https://cdn.jsdelivr.net/npm/emojibase-data@{version}"
output = pathlib.Path(__file__).resolve().parent.parent / "Sources/TookiKit/Emoji/EmojiData.swift"


def fetch(path):
    with urllib.request.urlopen(f"{base}/{path}") as response:
        return json.load(response)


resolved_version = fetch("package.json")["version"]
emoji = fetch("en/compact.json")
shortcodes = fetch("en/shortcodes/github.json")
groups = sorted(fetch("en/messages.json")["groups"], key=lambda group: group["order"])

# "Components" holds skin tone and hair swatches, which aren't emoji on their own.
kept_groups = [group for group in groups if group["key"] != "component"]
group_index = {group["order"]: index for index, group in enumerate(kept_groups)}
group_names = [" ".join(word.capitalize() for word in group["message"].split(" ")) for group in kept_groups]


def clean(words):
    return ",".join(word.replace(",", " ").replace("\t", " ").strip() for word in words)


lines = []
for item in sorted(emoji, key=lambda item: item.get("order", 1 << 30)):
    if item.get("group") not in group_index:
        continue
    codes = shortcodes.get(item["hexcode"], [])
    codes = [codes] if isinstance(codes, str) else codes
    fields = [item["unicode"], item["label"].lower(), str(group_index[item["group"]]), clean(item.get("tags", [])), clean(codes)]
    lines.append("\t".join(fields))

names = ", ".join(json.dumps(name) for name in group_names)
output.write_text(
    f"""// Generated by scripts/update-emoji.py from emojibase-data {resolved_version}. Don't edit by hand.

extension EmojiCatalog {{
    static let dataVersion = "{resolved_version}"
    static let groupNames = [{names}]

    /// One emoji per line, tab-separated: character, name, group index, keywords, shortcodes.
    /// Keywords and shortcodes are comma-separated.
    static let data = #\"\"\"
{chr(10).join(lines)}
\"\"\"#
}}
"""
)
print(f"Wrote {len(lines)} emoji from emojibase-data {resolved_version} to {output.relative_to(output.parents[3])}")
