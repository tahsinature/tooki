import AppKit
import TookiKit

extension NSPasteboard.PasteboardType {
    /// Community convention: clipboard managers skip these.
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}

/// Inserts text into the frontmost app by pasting it.
@MainActor
enum Paster {
    /// - Parameters:
    ///   - cursorOffsetFromEnd: moves the cursor this many characters left after pasting.
    ///   - temporary: marks the text as transient and restores the previous clipboard afterwards.
    static func paste(_ text: String, cursorOffsetFromEnd: Int = 0, temporary: Bool = true) {
        let pasteboard = NSPasteboard.general
        let previous = temporary ? snapshot(of: pasteboard) : nil

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if temporary { pasteboard.setData(Data(), forType: .transient) }
        let ourChangeCount = pasteboard.changeCount

        SyntheticEvent.press(KeyCode.v, flags: .maskCommand)

        Task {
            if cursorOffsetFromEnd > 0 {
                try? await Task.sleep(for: .milliseconds(60))
                for _ in 0..<cursorOffsetFromEnd { SyntheticEvent.press(KeyCode.leftArrow) }
            }
            guard let previous else { return }
            try? await Task.sleep(for: .milliseconds(400))
            // Only restore if nothing else touched the clipboard meanwhile.
            if pasteboard.changeCount == ourChangeCount { restore(previous, to: pasteboard) }
        }
    }

    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    /// Presses ⌘V in the frontmost app.
    static func pressPaste() {
        SyntheticEvent.press(KeyCode.v, flags: .maskCommand)
    }

    static func copy(fileURLs: [URL]) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.writeObjects(fileURLs as [NSURL])
    }

    /// Adds TIFF as well, since some older apps only accept that.
    static func copy(imagePNG png: Data) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
        if let tiff = NSImage(data: png)?.tiffRepresentation {
            pasteboard.setData(tiff, forType: .tiff)
        }
    }

    private static func snapshot(of pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { contents[type] = data }
            }
            return contents
        }
    }

    private static func restore(_ snapshot: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = snapshot.map { contents in
            let item = NSPasteboardItem()
            for (type, data) in contents { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
