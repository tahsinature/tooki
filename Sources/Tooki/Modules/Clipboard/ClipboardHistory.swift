import AppKit
import Observation
import TookiKit

/// Records copied text and images. Skips password managers and content marked as concealed or transient.
/// History is stored in Application Support, never in the shareable config folder.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var log = ClipboardLog()

    @ObservationIgnored private var config = ClipboardConfig()
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private let fileURL = StoragePaths.dataDirectory.appending(path: "clipboard-history.json")

    var items: [ClipboardItem] { log.items }

    func load() {
        guard let data = JSONFile.read(fileURL),
              let saved = try? JSONFile.decoder.decode(ClipboardLog.self, from: data)
        else { return }
        log = saved
        for item in log.items {
            if let image = item.image, image.recognizedText == nil { recognizeText(in: image) }
        }
    }

    func apply(_ config: ClipboardConfig) {
        self.config = config
        log.trim(maxItems: config.maxItems, maxImages: config.maxImages)
        if config.enabled {
            startPolling()
        } else {
            timer?.invalidate()
            timer = nil
        }
        save()
    }

    func paste(_ item: ClipboardItem) {
        copy(item)
        Paster.pressPaste()
    }

    func copy(_ item: ClipboardItem) {
        if let image = item.image {
            if let png = ClipboardImageStore.data(for: image) { Paster.copy(imagePNG: png) }
        } else if let files = item.files {
            Paster.copy(fileURLs: files.map { URL(fileURLWithPath: $0) })
        } else {
            Paster.copy(item.text)
        }
    }

    func togglePin(_ item: ClipboardItem) {
        log.togglePin(id: item.id)
        save()
    }

    func remove(_ item: ClipboardItem) {
        log.remove(id: item.id)
        save()
    }

    func clear() {
        log.removeAll()
        save()
    }

    private func startPolling() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
    }

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        let skippedTypes: [NSPasteboard.PasteboardType] = [.concealed, .transient, .autoGenerated]
        guard !types.contains(where: skippedTypes.contains) else { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let sourceApp, config.ignoredApps.contains(sourceApp) { return }

        if let files = Self.fileURLs(on: pasteboard) {
            let names = files.map(\.lastPathComponent).joined(separator: "\n")
            record(ClipboardItem(text: names, files: files.map(\.path), sourceApp: sourceApp))
        } else if let text = pasteboard.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            record(ClipboardItem(text: text, sourceApp: sourceApp))
        } else if config.maxImages > 0, var image = ClipboardImageStore.save(from: pasteboard) {
            // Copying the same image again reuses the text already found in it.
            image.recognizedText = log.items.first { $0.image?.fileName == image.fileName }?.image?.recognizedText
            record(ClipboardItem(image: image, sourceApp: sourceApp))
            if image.recognizedText == nil { recognizeText(in: image) }
        }
    }

    /// Finder puts file URLs and their names as text on the pasteboard; the files win.
    private static func fileURLs(on pasteboard: NSPasteboard) -> [URL]? {
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        return urls?.isEmpty == false ? urls : nil
    }

    private func record(_ item: ClipboardItem) {
        log.record(item, maxItems: config.maxItems, maxImages: config.maxImages)
        save()
    }

    private func recognizeText(in image: ClipboardImage) {
        Task {
            let text = await TextRecognizer.recognizeText(in: ClipboardImageStore.url(for: image))
            log.setRecognizedText(text, forImage: image.fileName)
            save()
        }
    }

    /// Also deletes image files that dropped out of the history.
    private func save() {
        ClipboardImageStore.removeUnused(keeping: log.imageFileNames)
        guard config.persistHistory else {
            try? FileManager.default.removeItem(at: fileURL)
            return
        }
        guard let data = try? JSONFile.encoder.encode(log) else { return }
        try? JSONFile.write(data, to: fileURL)
    }
}
